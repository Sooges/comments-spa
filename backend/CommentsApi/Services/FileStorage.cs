namespace CommentsApi.Services;

public class FileStorage : IFileStorage
{
    private readonly string _folder;

    public FileStorage(IConfiguration configuration, IWebHostEnvironment environment)
    {
        // the folder can be changed in the settings, for example to a Docker volume
        var configured = configuration["Storage:UploadsPath"];
        _folder = string.IsNullOrWhiteSpace(configured)
            ? Path.Combine(environment.ContentRootPath, "uploads")
            : configured;

        Directory.CreateDirectory(_folder);
    }

    public async Task<string> SaveAsync(byte[] content, string extension)
    {
        // the name is generated by the server, so the name of the uploaded file is never used on the disk
        var storedFileName = Guid.NewGuid().ToString("N") + extension;
        await File.WriteAllBytesAsync(Path.Combine(_folder, storedFileName), content);
        return storedFileName;
    }

    public Stream? Open(string storedFileName)
    {
        var path = GetPath(storedFileName);
        return File.Exists(path) ? File.OpenRead(path) : null;
    }

    public void Delete(string storedFileName)
    {
        var path = GetPath(storedFileName);
        if (File.Exists(path))
        {
            File.Delete(path);
        }
    }

    private string GetPath(string storedFileName)
    {
        // protection from names like "..\..\secret.txt"
        return Path.Combine(_folder, Path.GetFileName(storedFileName));
    }
}
